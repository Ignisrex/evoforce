package com.silverignis.components;

public final class GridBounds {
    public final int minCol, maxCol, minRow, maxRow;

    public GridBounds(int minCol, int maxCol, int minRow, int maxRow){
        this.minCol = minCol;
        this.maxCol = maxCol;
        this.minRow = minRow;
        this.maxRow = maxRow;
    }
}

